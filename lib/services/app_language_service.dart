  Future<void> initialize() async {
    final preferences = await SharedPreferences.getInstance();
    final saved = preferences.getString(_storageKey) ?? 'system';
    code.value = languages.any((language) => language.code == saved)
        ? saved
        : 'system';
  }

  Future<void> select(String value) async {
    if (!languages.any((language) => language.code == value)) return;
    code.value = value;
    final preferences = await SharedPreferences.getInstance();
    await preferences.setString(_storageKey, value);
  }

  Locale? get locale => code.value == 'system' ? null : Locale(code.value);

