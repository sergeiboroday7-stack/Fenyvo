        ? WidgetsBinding.instance.platformDispatcher.locale.languageCode
        : code.value;
    final translations =
        _authTranslations[selected] ?? _authTranslations['en']!;
    return translations[key] ?? _authTranslations['en']![key] ?? key;
  }

