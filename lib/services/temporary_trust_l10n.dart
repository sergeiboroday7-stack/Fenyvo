/// Presentation-only localization. Never translates user ciphertext or
/// sends text to an external translation service.
class TemporaryTrustL10n {
  TemporaryTrustL10n._();
  static String get languageCode {
    final selected = AppLanguageService.instance.code.value;
    return selected == 'system'
        ? WidgetsBinding.instance.platformDispatcher.locale.languageCode
        : selected;
  }

  static String text(String source) {
    if (languageCode == 'ru') return source;
    final resolved = _resolveTemplate(source);
    final translated = (_translations[languageCode] ?? _translations['en']!)[resolved.$1]
        ?? _translations['en']![resolved.$1] ?? source;
    var result = translated;
    for (final entry in resolved.$2.entries) {
      result = result.replaceAll('{${entry.key}}', entry.value);
    }
    return result;
  }

  static (String, Map<String, String>) _resolveTemplate(String text) {
    final patterns = <(RegExp, String, List<String>)>[
      (RegExp(r"^Активные чаты: (\d+)$"), "Активные чаты: {count}", ['count']),
      (RegExp(r"^Ожидают: (\d+)$"), "Ожидают: {count}", ['count']),
      (RegExp(r"^Непрочитанных: (\d+)$"), "Непрочитанных: {count}", ['count']),
      (RegExp(r"^(\d+) · (\d+) ждут$"), "{active} · {count} ждут", ['active', 'count']),
      (RegExp(r"^(\d+) · (\d+) новых$"), "{active} · {count} новых", ['active', 'count']),
      (RegExp(r"^E2EE · до (.+)$"), "E2EE · до {time}", ['time']),
      (RegExp(r"^Собеседник назвал себя @(.+)$"), "Собеседник назвал себя @{user}", ['user']),
    ];
    for (final pattern in patterns) {
      final match = pattern.$1.firstMatch(text);
      if (match == null) continue;
      final args = <String, String>{};
      for (var i = 0; i < pattern.$3.length; i++) {
        args[pattern.$3[i]] = match.group(i + 1)!;
      }
      return (pattern.$2, args);
    }
    return (text, const <String, String>{});
  }

