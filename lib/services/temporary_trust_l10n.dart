/// Listens to the app-wide language choice, including changes while a
/// temporary chat is open. Does not mutate session state.
class TemporaryTrustText extends StatelessWidget {
  const TemporaryTrustText(this.data, {super.key, this.style, this.textAlign, this.maxLines, this.overflow, this.softWrap});
  final String data;
  final TextStyle? style;
  final TextAlign? textAlign;
  final int? maxLines;
  final TextOverflow? overflow;
  final bool? softWrap;
  @override
  Widget build(BuildContext context) => ValueListenableBuilder<String>(
    valueListenable: AppLanguageService.instance.code,
    builder: (_, __, ___) => Text(
      TemporaryTrustL10n.text(data),
      style: style, textAlign: textAlign, maxLines: maxLines,
      overflow: overflow, softWrap: softWrap,
    ),
  );
}
